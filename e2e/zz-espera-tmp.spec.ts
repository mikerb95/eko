import { expect, test } from '@playwright/test'
test('captura espera', async ({ browser }) => {
  const ctx = await browser.newContext({ viewport: { width: 1600, height: 900 } })
  const p = await ctx.newPage()
  expect((await p.request.post('/api/admin/login', { data: { username: 'admin', password: 'ekosolv2026*' } })).ok()).toBeTruthy()
  await p.goto('/academia/taller/1')
  await expect(p.locator('body')).toHaveClass(/tl-on/)
  await p.keyboard.press('ArrowRight')
  await p.waitForTimeout(800)
  const r = await p.request.post('/api/academia/taller', { data: { accion: 'aviso', n: 1, minutos: 15 } })
  expect(r.ok(), await r.text()).toBeTruthy()
  await expect(p.locator('.tl-espera.on')).toBeVisible({ timeout: 8000 })
  await p.waitForTimeout(4000)
  await p.screenshot({ path: '/tmp/claude-1000/-home-mike-dev-work-github-com-eko/b82b2565-ed91-4e89-856f-6744522eda9c/scratchpad/espera-1.png' })
  const otro = await browser.newContext()
  const r2 = await otro.request.post('/api/academia/sala', { data: { accion: 'registrar', nombre: 'Ana María', apellido: 'Pérez', correo: 'ana@ekosolv.com', area: 'operaciones' } })
  expect(r2.ok(), await r2.text()).toBeTruthy()
  await expect(p.locator('.tl-espera .clawd-globo')).toHaveText('¡Hola, Ana!', { timeout: 8000 })
  await p.waitForTimeout(500)
  await p.screenshot({ path: '/tmp/claude-1000/-home-mike-dev-work-github-com-eko/b82b2565-ed91-4e89-856f-6744522eda9c/scratchpad/espera-2.png' })
  for (const [n, c] of [['Luis', 'l@e.com'], ['Marta', 'm@e.com'], ['Juan', 'j@e.com']]) await otro.request.post('/api/academia/sala', { data: { accion: 'registrar', nombre: n, apellido: 'X', correo: c, area: 'operaciones' } })
  await expect(p.locator('.tl-espera .clawd-globo')).toContainText('más', { timeout: 8000 })
  await p.screenshot({ path: '/tmp/claude-1000/-home-mike-dev-work-github-com-eko/b82b2565-ed91-4e89-856f-6744522eda9c/scratchpad/espera-3.png' })
})
